from collections import defaultdict
from datetime import date, timedelta

from sqlalchemy.orm import Session, joinedload

from app.models import ShoppingItem, ShoppingList, WeeklyMenu
from app.services.household import get_household
from app.services.menu import get_week
from app.services.timeutil import monday_of


def _key(name: str, unit: str) -> tuple[str, str]:
    return name.strip().lower(), unit.strip().lower()


def _scale(qty: float, base: int, household_size: int) -> float:
    if base <= 0:
        return qty
    scaled = qty * (household_size / base)
    return round(scaled, 2)


def build_shopping_list(db: Session, week_start: date | None = None) -> ShoppingList:
    household = get_household(db)
    menu = get_week(db, week_start)
    if menu is None:
        raise ValueError("No weekly menu found. Generate a menu first.")

    existing = db.query(ShoppingList).filter(ShoppingList.weekly_menu_id == menu.id).first()
    if existing:
        db.query(ShoppingItem).filter(ShoppingItem.shopping_list_id == existing.id).delete()
        shopping = existing
        shopping.status = "open"
    else:
        shopping = ShoppingList(weekly_menu_id=menu.id, status="open")
        db.add(shopping)
        db.flush()

    buckets: dict[tuple[str, str], dict] = defaultdict(
        lambda: {"quantity": 0.0, "needed_by": None, "category": "other", "display": ""}
    )
    for item in menu.items:
        recipe = item.recipe
        if recipe is None:
            continue
        factor_servings = item.servings or household.size
        for ingredient in recipe.ingredients or []:
            name = str(ingredient.get("name", "")).strip()
            unit = str(ingredient.get("unit", "")).strip()
            if not name:
                continue
            qty = _scale(float(ingredient.get("qty") or 0), recipe.base_servings, factor_servings)
            bucket = buckets[_key(name, unit)]
            bucket["quantity"] += qty
            bucket["display"] = name
            bucket["category"] = ingredient.get("category") or bucket["category"]
            needed = item.meal_date
            if bucket["needed_by"] is None or needed < bucket["needed_by"]:
                bucket["needed_by"] = needed

    for (_name, unit), data in sorted(buckets.items()):
        db.add(
            ShoppingItem(
                shopping_list_id=shopping.id,
                name=data["display"],
                quantity=round(data["quantity"], 2),
                unit=unit,
                category=data["category"],
                needed_by=data["needed_by"],
                purchased=False,
            )
        )
    db.commit()
    return (
        db.query(ShoppingList)
        .options(joinedload(ShoppingList.items))
        .filter(ShoppingList.id == shopping.id)
        .first()
    )


def latest_list(db: Session) -> ShoppingList | None:
    return (
        db.query(ShoppingList)
        .options(joinedload(ShoppingList.items))
        .order_by(ShoppingList.id.desc())
        .first()
    )


def toggle_item(db: Session, item_id: int, purchased: bool) -> ShoppingItem:
    item = db.get(ShoppingItem, item_id)
    if item is None:
        raise KeyError(item_id)
    item.purchased = purchased
    db.commit()
    db.refresh(item)
    return item


def items_due_for_reminder(db: Session, day: date, reminder_days: int) -> list[ShoppingItem]:
    target = day + timedelta(days=reminder_days)
    return (
        db.query(ShoppingItem)
        .join(ShoppingList)
        .filter(ShoppingItem.needed_by == target, ShoppingItem.purchased.is_(False))
        .all()
    )


def format_list_message(items: list[ShoppingItem], needed_by: date) -> str:
    if not items:
        return ""
    lines = [f"Smart Kitchen reminder: buy these by {needed_by.isoformat()}"]
    grouped: dict[str, list[ShoppingItem]] = defaultdict(list)
    for item in items:
        grouped[item.category].append(item)
    for category, group in grouped.items():
        lines.append(f"\n{category.replace('_', ' ').title()}")
        for item in group:
            qty = int(item.quantity) if item.quantity.is_integer() else item.quantity
            lines.append(f"- {item.name}: {qty} {item.unit}".strip())
    lines.append("\nThis message is generated by Smart Kitchen AI.")
    return "\n".join(lines)


def week_start_from_list(db: Session, shopping: ShoppingList) -> date | None:
    if shopping.weekly_menu_id is None:
        return None
    menu = db.get(WeeklyMenu, shopping.weekly_menu_id)
    return monday_of(menu.week_start) if menu else None
